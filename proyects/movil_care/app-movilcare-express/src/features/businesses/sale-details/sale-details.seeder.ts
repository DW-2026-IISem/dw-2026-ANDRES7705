import { faker } from "@faker-js/faker";
import { Product } from "../products/products.model";
import { Sale } from "../sales/sales.model";
import { SaleDetail } from "./sale-details.model";
import { SerializedUnit } from "../serialized-units/serialized-units.model";

export async function seedSaleDetails(count: number): Promise<number> {
  if (!Number.isSafeInteger(count) || count < 0) {
    throw new RangeError("Sale detail seed count must be a non-negative integer");
  }
  if (count === 0) {
    console.log("⏭️  sale_details: count=0, se omite");
    return 0;
  }

  const existing = await SaleDetail.count();
  if (existing > 0) {
    console.log(`⏭️  sale_details: ya hay ${existing} registro(s), se omite seeder`);
    return 0;
  }

  const sales = await Sale.findAll({ where: { state: "DRAFT" } });
  if (sales.length === 0) {
    console.log("⏭️  sale_details: no hay ventas DRAFT, se omite seeder");
    return 0;
  }

  const products = await Product.findAll({ where: { isActive: true } });
  const stockRemaining = new Map(
    products.filter((product) => !product.requiresSerial).map((product) => [product.id, product.stockQuantity])
  );
  const serializedUnits = await SerializedUnit.findAll({
    where: { state: "IN_STOCK", isActive: true },
  });
  const serialProductIds = new Set(serializedUnits.map((unit) => unit.productId));
  const candidates = products.filter(
    (product) =>
      (product.requiresSerial && serialProductIds.has(product.id)) ||
      (!product.requiresSerial && product.stockQuantity > 0)
  );
  if (candidates.length === 0) {
    console.log("⏭️  sale_details: no hay productos con inventario disponible; ajuste stock o unidades serializadas y reintente");
    return 0;
  }

  const availableUnits = [...serializedUnits];
  const totals = new Map<number, { subtotal: number; discount: number; taxes: number }>();
  const rows: Array<{
    saleId: number;
    productId: number;
    serializedUnitId: number | null;
    quantity: number;
    unitPrice: string;
    discount: string;
    taxPercentage: string;
    total: string;
    notes: string;
    isActive: boolean;
  }> = [];

  for (let index = 0; index < count; index += 1) {
    const eligible = candidates.filter((product) =>
      product.requiresSerial
        ? availableUnits.some((unit) => unit.productId === product.id)
        : (stockRemaining.get(product.id) ?? 0) > 0
    );
    if (eligible.length === 0) break;

    const product = faker.helpers.arrayElement(eligible);
    const sale = sales[index % sales.length];
    let quantity: number;
    let serializedUnitId: number | null = null;
    if (product.requiresSerial) {
      quantity = 1;
      const unitIndex = availableUnits.findIndex((unit) => unit.productId === product.id);
      const [unit] = availableUnits.splice(unitIndex, 1);
      serializedUnitId = unit.id;
    } else {
      const remaining = stockRemaining.get(product.id) ?? 0;
      quantity = faker.number.int({ min: 1, max: Math.min(3, remaining) });
      stockRemaining.set(product.id, remaining - quantity);
    }

    const unitPrice = Number(product.price);
    const taxPercentage = Number(product.taxPercentage);
    const lineSubtotal = quantity * unitPrice;
    const lineTaxes = (lineSubtotal * taxPercentage) / 100;
    const lineTotal = lineSubtotal + lineTaxes;
    rows.push({
      saleId: sale.id,
      productId: product.id,
      serializedUnitId,
      quantity,
      unitPrice: unitPrice.toFixed(2),
      discount: "0.00",
      taxPercentage: taxPercentage.toFixed(2),
      total: lineTotal.toFixed(2),
      notes: "Generated by Faker",
      isActive: true,
    });
    const totalsForSale = totals.get(sale.id) ?? { subtotal: 0, discount: 0, taxes: 0 };
    totalsForSale.subtotal += lineSubtotal;
    totalsForSale.taxes += lineTaxes;
    totals.set(sale.id, totalsForSale);
  }

  if (rows.length === 0) {
    console.log("⏭️  sale_details: no se encontraron líneas compatibles con el inventario");
    return 0;
  }

  await SaleDetail.bulkCreate(rows);
  for (const sale of sales) {
    const values = totals.get(sale.id);
    if (!values) continue;
    await sale.update({
      subtotal: values.subtotal.toFixed(2),
      discount: values.discount.toFixed(2),
      taxes: values.taxes.toFixed(2),
      total: (values.subtotal + values.taxes - values.discount).toFixed(2),
    });
  }
  console.log(`✅ sale_details: insertadas ${rows.length} línea(s) de venta en borrador`);
  return rows.length;
}
